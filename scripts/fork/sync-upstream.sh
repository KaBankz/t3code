#!/bin/sh
# Rebases the fork onto upstream/main and regenerates the branding commit on top.
# The branding commit is generated, never hand-edited, so it never needs conflict
# resolution: it is dropped before the rebase and rebuilt after it. Safe to rerun
# after resolving a conflict in the hand-written commits.
set -eu

GENERATED_SUBJECT="chore(fork): apply fork branding (generated by scripts/fork/rebrand.ts)"

cd "$(git rev-parse --show-toplevel)"

if ! git diff --quiet || ! git diff --cached --quiet; then
  echo "Commit or stash your changes first." >&2
  exit 1
fi

git fetch upstream

if [ "$(git log -1 --format=%s)" = "$GENERATED_SUBJECT" ]; then
  git reset --hard HEAD~1
fi

git rebase upstream/main

node scripts/fork/rebrand.ts
if ! git diff --quiet; then
  git commit --quiet --all --message "$GENERATED_SUBJECT"
fi

git log --oneline upstream/main..HEAD
